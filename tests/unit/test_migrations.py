import os
import sqlite3
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def test_alembic_upgrade_and_downgrade_on_empty_sqlite(tmp_path):
    db_file = tmp_path / "mig.sqlite3"
    env = {**os.environ, "DATABASE_URL": f"sqlite:///{db_file}"}
    alembic = Path(sys.executable).parent / "alembic"
    subprocess.run(
        [str(alembic), "upgrade", "head"], cwd=ROOT, env=env, check=True, capture_output=True
    )
    tables = {
        r[0]
        for r in sqlite3.connect(db_file).execute(
            "select name from sqlite_master where type='table'"
        )
    }
    assert {
        "companies",
        "filings",
        "financial_facts",
        "ingestion_runs",
        "api_keys",
        "api_usage",
        "company_watches",
        "notification_deliveries",
        "audit_events",
    } <= tables
    subprocess.run(
        [str(alembic), "downgrade", "base"], cwd=ROOT, env=env, check=True, capture_output=True
    )
    tables = {
        r[0]
        for r in sqlite3.connect(db_file).execute(
            "select name from sqlite_master where type='table'"
        )
    }
    assert "companies" not in tables


def test_models_match_migration_metadata():
    """The autogenerated migration must cover every model table."""
    import re

    from app.db.models import Base

    text = (ROOT / "app/db/migrations/versions").glob("*.py")
    joined = "\n".join(p.read_text() for p in text)
    for table in Base.metadata.tables:
        assert re.search(rf"create_table\(\s*['\"]{table}['\"]", joined), table
