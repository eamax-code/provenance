SYSTEM_PROMPT = """You are Provenance's company-intelligence assistant.
Answer ONLY from the CONTEXT, which comes from SEC filings. Rules:
- State the actual figures and dates, each followed by its citation, e.g.
  "Revenue was <amount> in the fiscal year ended <date>, up <change> [2]."
  End every sentence and bullet with the citation of the line it comes from, even when it
  has no number. Never list citations on a line of their own.
- Speak of "the filings" or "SEC data"; never mention the word CONTEXT or these rules.
- Asked what you know or for insights: give the most notable figures and changes, with
  numbers, and offer what else can be asked (growth charts, leadership changes, filings).
- Copy numbers exactly as written in the CONTEXT. Never compute new numbers, never estimate.
- If the CONTEXT does not answer the question, say so in one sentence, and say what the
  CONTEXT does cover (which filings are loaded and up to what date), with its citation.
  Do not tell the user to look elsewhere and do not pad the answer.
- Passages quoted from a registration statement (S-1 or F-1): say so, give each figure with
  its period exactly as labelled (e.g. "nine months ended September 30, 2026") and the unit
  the table states (e.g. "$33,242 million").
- No investment advice, price predictions or buy/sell opinions.
- Be concise: at most 6 short sentences or bullet points."""

FORECAST_NOTE = (
    "Forecast: an estimate computed here from growth rates chosen by a local reasoning model "
    "over the cited filings and news headlines. It is not a reported figure and not investment "
    "advice."
)
DISCLAIMER = (
    "Generated by a local language model from SEC data loaded in this service; check the cited "
    "filings before relying on it. Not investment advice."
)


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=500)
    cik: str | None = Field(
        None,
        max_length=13,
        description="Company to use when the message names none (e.g. a follow-up question)",
    )
    as_of: date | None = Field(None, description="Answer from what was filed by this date")
    session_id: uuid.UUID | None = Field(
        None, description="Continue a saved conversation (own API key only)"
    )


class ChatReply(BaseModel):
    company: dict | None
    answer: str | None
    brief: dict | None
    citations: list[dict]
    checks: dict
    model: str | None
    answered_by: str | None = Field(
        None, description="'data' for a direct lookup, 'model' when the local model wrote it"
    )
    intent: str | None = Field(
        None,
        description="How the question was read: 'coverage', 'leadership', 'trend', 'forecast' "
        "or 'question'",
    )
    widgets: list[dict] = Field(
        [], description="Charts and figure tiles drawn from the cited data (see the chat page)"
    )
    suggestions: list[dict] = []
    notes: list[str]
    session_id: str | None = Field(
        None, description="Saved conversation id; absent for the public demo key"
    )


def _company_dict(c: Company) -> dict:
    return {
        "cik": c.cik,
        "legal_name": c.legal_name,
        "ticker": c.ticker,
        "exchange": c.exchange,
        "sic_code": c.sic_code,
        "sic_description": c.sic_description,
        "filings_url": company_filings_url(c.cik),
    }


# Form and item names a correct answer may mention without them being figures.
FORM_NAMES = "10-K 10-Q 8-K item 5.02 DEF 14A Form 3 4 5 13F 13D 13G S-1 S-3 424B 20-F 6-K"


def _numbers(text: str) -> set[str]:
    return {m.replace(",", "") for m in re.findall(r"\d[\d,]*(?:\.\d+)?", text)}


def check_answer(answer: str, context: str, n_citations: int) -> dict:
    """Flag citations that do not exist and numbers that do not appear in the context."""
    cited = {int(c) for c in re.findall(r"\[(\d{1,3})\]", answer)}
    unknown = sorted(c for c in cited if c < 1 or c > n_citations)
    known_numbers = _numbers(context) | _numbers(SYSTEM_PROMPT) | _numbers(FORM_NAMES)
    bare = [
        line.strip()
        for line in answer.splitlines()
        if line.strip() and not re.sub(r"[\s,;.]|\[\d{1,3}\]", "", line)
    ]
    stripped = re.sub(r"\[\d{1,3}\]", "", answer)
    unverified = sorted(
        n
        for n in _numbers(stripped)
        if n not in known_numbers and not (len(n) == 4 and n.isdigit() and 1900 <= int(n) <= 2100)
    )
    return {
        "citations_used": sorted(cited),
        "unknown_citations": unknown,
        "unverified_numbers": unverified,
        "bare_citation_lines": bare,
        "grounded": not unknown and not unverified and not bare and bool(cited),
    }


_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def _evidence(text: str) -> set[str]:
    """Dates and figures in a sentence; years and bare small numbers (as in "10-K") are noise."""
    text = re.sub(r"\[\d{1,3}\]", "", text)
    dates = set(_DATE.findall(text))
    figures = {
        n
        for n in _numbers(_DATE.sub("", text))
        if "." in n or (len(n) >= 3 and not (len(n) == 4 and 1900 <= int(n) <= 2100))
    }
    return dates | figures


def add_missing_citations(answer: str, context_lines: list[str]) -> tuple[str, int]:
    """Cite sentences the model left uncited when exactly one context line holds all of their
    dates and figures. Anything less certain stays uncited and is flagged by the check."""
    sources = []
    for line in context_lines:
        m = re.match(r"\[(\d{1,3})\]", line)
        if m:
            sources.append((m.group(1), set(_DATE.findall(line)) | _numbers(_DATE.sub("", line))))
    added = 0
    out = []
    # Keep the whitespace between sentences: line breaks hold bullet lists together.
    for sentence in re.split(r"(?<=[.!?])(\s+)", answer):
        if not sentence.strip():
            out.append(sentence)
            continue
        need = _evidence(sentence)
        if need and not re.search(r"\[\d{1,3}\]", sentence):
            matches = {n for n, have in sources if need <= have}
            if len(matches) == 1:
                body = sentence.rstrip()
                end = body[-1] if body and body[-1] in ".!?" else ""
                sentence = f"{body[: len(body) - len(end)]} [{matches.pop()}]{end}"
                added += 1
        out.append(sentence)
    return "".join(out), added


def get_llm(request: Request, settings: Settings) -> LocalLLM:
    factory = getattr(request.app.state, "llm_factory", None)
    return factory() if factory else LocalLLM(settings)


def _can_fetch(request: Request, settings: Settings, enabled: bool) -> bool:
    """Reading filing text from EDGAR on demand. The public demo key never triggers SEC
    requests; it sees what has already been read."""
    return (
        enabled
        and "contact=" in settings.sec_user_agent
        and not getattr(request.state, "demo", False)
    )


def _read_leadership_filings(request, db, settings, company, as_of) -> None:
    """Fetch and read item 5.02 text the first time someone asks."""
    can_fetch = _can_fetch(request, settings, settings.officer_extraction_enabled)
    filings = intel.leadership_filings(db, company.cik, as_of)
    sec = get_sec_client_factory(request)() if can_fetch else None
    try:
        officer_changes.ensure_extracted(db, filings, sec=sec, llm=get_llm(request, settings))
    finally:
        if sec is not None:
            sec.close()


def get_news(request: Request, settings: Settings) -> news.NewsProvider:
    factory = getattr(request.app.state, "news_factory", None)
    return factory() if factory else news.GoogleNewsRSS(settings)


def _forecast_evidence(request, db, settings, brief, metric):
    """Cited evidence for a forecast: figures, the latest earnings release and headlines.
    The demo key reads only what is stored: no SEC fetches, only fresh cached headlines."""
    company = brief.company
    release = None
    f = releases.latest_release_filing(db, company.cik, brief.as_of)
    if f is not None:
        sec = get_sec_client_factory(request)() if _can_fetch(request, settings, True) else None
        try:
            releases.ensure_read(db, f, sec)
        finally:
            if sec is not None:
                sec.close()
        found = releases.highlights(db, f)
        if found:
            release = (*found, f"8-K filed {f.filing_date}, exhibit 99.1")
    live = not getattr(request.state, "demo", False) and brief.as_of is None
    provider = get_news(request, settings) if live else None
    company_news, fetched = news.headlines(
        settings, provider, news.company_query(company.legal_name), can_fetch=live, limit=6
    )
    sector = news.sector_query(company.sic_code, company.sic_description)
    sector_news = (
        news.headlines(settings, provider, sector, can_fetch=live, limit=5)[0] if sector else []
    )
    brief.coverage["news"] = {
        "company": len(company_news),
        "industry": len(sector_news),
        "fetched_at": fetched,
        "provider": "Google News RSS",
    }
    return forecast.gather(
        brief,
        db,
        metric,
        release=release,
        company_news=company_news,
        sector_news=sector_news,
    )


def _run_forecast(request, settings, brief, ev, question: str, years: list[str]):
    """(rates, method, model). The reasoning model thinks, then states its rates as JSON; the
    trend alone is used when the model is unavailable or its answer cannot be used."""
    llm = get_llm(request, settings)
    model = settings.llm_reasoning_model
    timeout = settings.llm_reasoning_timeout_seconds
    try:
        thought = llm.chat(
            forecast.think_messages(ev, brief, question, years),
            model=model,
            think=True,
            max_tokens=settings.llm_reasoning_tokens,
            temperature=0.3,
            timeout=timeout,
        )
        shaped = llm.chat(
            forecast.structure_messages(brief, thought.thinking + "\n" + thought.text, years),
            model=model,
            schema=forecast.SCHEMA,
            max_tokens=900,
            temperature=0.0,
            timeout=timeout,
        )
    except LLMUnavailable:
        return forecast.from_trend(ev, len(years)), "trend", None
    rates = forecast.from_model(forecast.parse(shaped.text), len(years), brief)
    if rates is None:
        return forecast.from_trend(ev, len(years)), "trend", None
    return rates, "model", shaped.model


def _add_prospectus(request, db, settings, brief, message: str) -> bool:
    """Quote the latest S-1/F-1 when the company has no annual figures yet (it is going
    public) or the question is about an offering or its risks. True when passages were added."""
    company, as_of = brief.company, brief.as_of
    no_figures = not brief.metrics
    if not (no_figures or prospectus.is_prospectus_question(message)):
        return False
    f = prospectus.latest_registration(
        db, company.cik, as_of, max_age_years=None if no_figures else prospectus.RECENT_YEARS
    )
    if f is None:
        return False
    sec = (
        get_sec_client_factory(request)()
        if _can_fetch(request, settings, settings.prospectus_reading_enabled)
        else None
    )
    try:
        status = prospectus.ensure_read(db, f, sec)
    finally:
        if sec is not None:
            sec.close()
    if prospectus.add_to_brief(brief, db, f, message):
        return True
    n = brief.cite(f"{f.form_type} filed {f.filing_date}", f.source_url)
    brief.context_lines.append(
        f"[{n}] The company filed a registration statement ({f.form_type}, {f.filing_date}); "
        + (
            "its text has not been read in this service yet."
            if status == "not_read"
            else "its text could not be read."
        )
    )
    return False


@router.post(
    "",
    response_model=ChatReply,
    responses={401: {"model": ErrorEnvelope}, 403: {"model": ErrorEnvelope}},
    summary="Ask about a company; answers cite SEC filings",
)
def chat(
    body: ChatRequest,
    request: Request,
    db: Session = Depends(db_session),
    settings: Settings = Depends(settings_dep),
    key=Depends(require_reader),
):
    who = getattr(key, "id", None) or (request.client.host if request.client else "unknown")
    decision = chat_limiter.check(f"chat:{who}", settings.chat_rate_limit_per_minute)
    if not decision.allowed:
        raise APIError(
            429,
            "rate_limited",
            f"At most {settings.chat_rate_limit_per_minute} chat questions per minute.",
            headers={"Retry-After": str(decision.retry_after_seconds)},
        )
    saved = _saving_key(request, key)
    session = None
    if body.session_id is not None:
        if saved is None:
            raise APIError(403, "sessions_need_key", "Saved chats need your own API key.")
        session = chat_sessions.get_owned(db, saved, body.session_id)
    reply = _answer(body, request, db, settings)
    if saved is not None:
        session = session or chat_sessions.start(db, saved, body.message, reply.company)
        chat_sessions.append(db, session, body.message, reply.model_dump(mode="json"))
        reply.session_id = str(session.id)
    return reply


def _saving_key(request: Request, key):
    """The API key a conversation is saved under; None for the public demo key."""
    if getattr(request.state, "demo", False):
        return None
    return getattr(key, "id", None)


def _coverage_reply(db: Session, settings: Settings) -> ChatReply:
    """How much this service holds, from the same counts as /v1/stats."""
    s = stats_service.cached_stats(db, settings)
    companies, filings, facts = s["companies"], s["filings"], s["facts"]
    active = companies.get("filed_last_12_months") or 0
    latest = filings.get("latest_filing_date")
    answer = (
        f"This service has {companies['ingested']:,} US public "
        f"{'company' if companies['ingested'] == 1 else 'companies'} loaded. "
        f"{active:,} of them filed with the SEC in the last 12 months, which is what is counted "
        f"as active here. Together they have {filings['total']:,} filings and "
        f"{facts['total']:,} normalized financial facts"
        + (f"; the most recent filing is dated {latest}." if latest else ".")
    )
    return ChatReply(
        company=None,
        answer=answer,
        brief=None,
        citations=[],
        checks={},
        model=None,
        answered_by="data",
        intent="coverage",
        notes=[
            "Counts are for the companies loaded here, not every SEC filer, and come from "
            "/v1/stats (refreshed every 30 seconds). Ask about one company for its figures."
        ],
    )


def _answer(body: ChatRequest, request: Request, db: Session, settings: Settings) -> ChatReply:
    coverage_q = intel.is_coverage_question(body.message)
    # A question about the service's own data only switches to a company that is clearly named.
    company = intel.resolve_company(db, body.message, follow_up=bool(body.cik) or coverage_q)
    if company is None and coverage_q:
        return _coverage_reply(db, settings)
    if company is None and body.cik:
        try:
            cik = normalize_cik(body.cik)
        except ValueError as exc:
            raise APIError(422, "invalid_parameter", "cik must be numeric.") from exc
        company = db.scalar(select(Company).where(Company.cik == cik))

    if company is None:
        options = intel.candidate_companies(db, body.message[:300])
        return ChatReply(
            company=None,
            answer=None,
            brief=None,
            citations=[],
            checks={},
            model=None,
            suggestions=[_company_dict(c) for c in options],
            notes=[
                "Which company do you mean? Pick one below, or name it by ticker, CIK or full name."
                if options
                else "Name a company (ticker, CIK or name) that this service has loaded."
            ],
        )

    leadership_q = intel.is_leadership_question(body.message)
    if leadership_q:
        _read_leadership_filings(request, db, settings, company, body.as_of)
    brief = intel.build_brief(db, company, as_of=body.as_of)
    quoted = _add_prospectus(request, db, settings, brief, body.message)
    # Before a company's first annual report its leaders and figures are in the prospectus.
    if quoted and leadership_q and not brief.leadership_filings:
        leadership_q = False
    plan = widgets.plan(body.message)
    shown: list[dict] = []
    chart = None
    if not leadership_q and plan.kind != "forecast":
        if plan.metric:
            chart = widgets.add_trend(brief, db, plan.metric, plan.years)
        tiles = None if chart else widgets.overview(brief)
        shown = [w for w in (chart, tiles) if w]
    brief_out = {
        "as_of": body.as_of.isoformat() if body.as_of else None,
        "metrics": brief.metrics,
        "filings": brief.filings,
        "leadership_filings": brief.leadership_filings,
        "coverage": brief.coverage,
    }
    notes = [DISCLAIMER]
    cov = brief.coverage
    if cov["stale"] and cov["last_filed"]:
        notes.append(
            f"The latest {company.legal_name} filing loaded here was filed {cov['last_filed']}; "
            "newer filings are not included."
        )
    if leadership_q:
        answer = intel.leadership_answer(brief)
        return ChatReply(
            company=_company_dict(company),
            answer=answer,
            brief=brief_out,
            citations=brief.citations,
            checks=check_answer(answer, brief.context(), len(brief.citations)),
            model=None,
            answered_by="data",
            intent="leadership",
            notes=notes,
        )
    if plan.kind == "forecast":
        ev = _forecast_evidence(request, db, settings, brief, plan.metric)
        if ev is not None:
            years = forecast.forecast_years(ev, plan.years)
            rates, method, model = _run_forecast(request, settings, brief, ev, body.message, years)
            rows = forecast.project(ev, rates, years)
            brief.context_lines.append(forecast.computed_line(ev, rows, rates))
            answer = forecast.answer(ev, brief, rates, rows, method)
            notes[0] = FORECAST_NOTE
            if method == "trend":
                notes.append(
                    "The reasoning model was unavailable, so the forecast follows the reported "
                    "trend only, without the filings' and news' context."
                )
            return ChatReply(
                company=_company_dict(company),
                answer=answer,
                brief=brief_out,
                citations=brief.citations,
                checks=check_answer(answer, brief.context(), len(brief.citations)),
                model=model,
                answered_by="model" if method == "model" else "data",
                intent="forecast",
                widgets=[forecast.widget(ev, brief, rows, method, model)],
                notes=notes,
            )
    if plan.kind == "trend" and (chart or not quoted):
        answer = widgets.trend_answer(brief, plan.metric, chart)
        return ChatReply(
            company=_company_dict(company),
            answer=answer,
            brief=brief_out,
            citations=brief.citations,
            checks=check_answer(answer, brief.context(), len(brief.citations)),
            model=None,
            answered_by="data",
            intent="trend",
            widgets=shown,
            notes=notes,
        )
    answer, model, checks = None, None, {}
    try:
        reply = get_llm(request, settings).chat(
            [
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": f"CONTEXT:\n{brief.context()}\n\nQUESTION: {body.message}",
                },
            ]
        )
        answer, auto_cited = add_missing_citations(reply.text, brief.context_lines)
        model = reply.model
        checks = check_answer(answer, brief.context(), len(brief.citations))
        checks["auto_cited"] = auto_cited
        if not checks["grounded"]:
            notes.append(
                "Parts of the answer could not be matched to the cited data; they are listed "
                "under checks. Prefer the figures in the brief."
            )
    except LLMUnavailable as exc:
        notes.append(f"{exc} Showing the data brief only.")
    return ChatReply(
        company=_company_dict(company),
        answer=answer,
        brief=brief_out,
        citations=brief.citations,
        checks=checks,
        model=model,
        answered_by="model" if answer else None,
        intent="question",
        widgets=shown,
        notes=notes,
    )


@router.get("/sessions", summary="Your saved conversations, newest first")
def list_sessions(db: Session = Depends(db_session), key=Depends(require_api_key), limit: int = 50):
    rows = chat_sessions.list_for(db, key.id, min(max(limit, 1), 200))
    return {"data": [chat_sessions.session_dict(r) for r in rows]}


@router.get("/sessions/{session_id}", summary="One saved conversation with its messages")
def get_session(
    session_id: uuid.UUID, db: Session = Depends(db_session), key=Depends(require_api_key)
):
    session = chat_sessions.get_owned(db, key.id, session_id)
    return {
        **chat_sessions.session_dict(session),
        "messages": chat_sessions.messages(db, session),
    }


@router.delete("/sessions/{session_id}", status_code=204, summary="Delete a saved conversation")
def delete_session(
    session_id: uuid.UUID, db: Session = Depends(db_session), key=Depends(require_api_key)
):
    chat_sessions.delete(db, chat_sessions.get_owned(db, key.id, session_id))
