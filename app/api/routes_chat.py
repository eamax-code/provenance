"""Company-intelligence chat: a cited brief from SEC data, phrased by a local language model."""

from __future__ import annotations

import re
from datetime import date

from fastapi import APIRouter, Depends, Request
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.api.dependencies import db_session, require_reader, settings_dep
from app.core.config import Settings
from app.core.errors import APIError
from app.core.rate_limits import FixedWindowRateLimiter
from app.db.models import Company
from app.schemas.common import ErrorEnvelope
from app.services import intel
from app.services.company_lookup import search_companies
from app.services.llm import LLMUnavailable, LocalLLM
from app.services.sec_client import normalize_cik

router = APIRouter(prefix="/v1/chat", tags=["chat"])
chat_limiter = FixedWindowRateLimiter(window_seconds=60)

SYSTEM_PROMPT = """You are Provenance's company-intelligence assistant.
Answer ONLY from the CONTEXT, which comes from SEC filings. Rules:
- Put the citation right after the statement it supports, e.g. "Revenue rose [2]."
  Never list citations on a line of their own.
- Copy numbers exactly as written in the CONTEXT. Never compute new numbers, never estimate.
- If the CONTEXT does not answer the question, say so in one sentence, and say what the
  CONTEXT does cover (which filings are loaded and up to what date), with its citation.
  Do not tell the user to look elsewhere and do not pad the answer.
- No investment advice, price predictions or buy/sell opinions.
- Be concise: at most 6 short sentences or bullet points."""

DISCLAIMER = (
    "Generated by a local language model from SEC data loaded in this service; check the cited "
    "filings before relying on it. Not investment advice."
)


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=500)
    cik: str | None = Field(
        None,
        max_length=13,
        description="Company to use when the message names none (e.g. a follow-up question)",
    )
    as_of: date | None = Field(None, description="Answer from what was filed by this date")


class ChatReply(BaseModel):
    company: dict | None
    answer: str | None
    brief: dict | None
    citations: list[dict]
    checks: dict
    model: str | None
    answered_by: str | None = Field(
        None, description="'data' for a direct lookup, 'model' when the local model wrote it"
    )
    suggestions: list[dict] = []
    notes: list[str]


def _company_dict(c: Company) -> dict:
    return {
        "cik": c.cik,
        "legal_name": c.legal_name,
        "ticker": c.ticker,
        "exchange": c.exchange,
        "sic_code": c.sic_code,
        "sic_description": c.sic_description,
        "source_url": c.source_url,
    }


# Form and item names a correct answer may mention without them being figures.
FORM_NAMES = "10-K 10-Q 8-K item 5.02 DEF 14A Form 3 4 5 13F 13D 13G S-1 S-3 424B 20-F 6-K"


def _numbers(text: str) -> set[str]:
    return {m.replace(",", "") for m in re.findall(r"\d[\d,]*(?:\.\d+)?", text)}


def check_answer(answer: str, context: str, n_citations: int) -> dict:
    """Flag citations that do not exist and numbers that do not appear in the context."""
    cited = {int(c) for c in re.findall(r"\[(\d{1,3})\]", answer)}
    unknown = sorted(c for c in cited if c < 1 or c > n_citations)
    known_numbers = _numbers(context) | _numbers(SYSTEM_PROMPT) | _numbers(FORM_NAMES)
    bare = [
        line.strip()
        for line in answer.splitlines()
        if line.strip() and not re.sub(r"[\s,;.]|\[\d{1,3}\]", "", line)
    ]
    stripped = re.sub(r"\[\d{1,3}\]", "", answer)
    unverified = sorted(
        n
        for n in _numbers(stripped)
        if n not in known_numbers and not (len(n) == 4 and n.isdigit() and 1900 <= int(n) <= 2100)
    )
    return {
        "citations_used": sorted(cited),
        "unknown_citations": unknown,
        "unverified_numbers": unverified,
        "bare_citation_lines": bare,
        "grounded": not unknown and not unverified and not bare and bool(cited),
    }


def _significant(text: str) -> set[str]:
    text = re.sub(r"\[\d{1,3}\]|\d{4}-\d{2}-\d{2}", "", text)
    return {
        n for n in _numbers(text) if not (len(n) == 4 and n.isdigit() and 1900 <= int(n) <= 2100)
    }


def add_missing_citations(answer: str, context_lines: list[str]) -> tuple[str, int]:
    """Cite sentences the model left uncited when one context line holds all of their numbers."""
    sources = []
    for line in context_lines:
        m = re.match(r"\[(\d{1,3})\]", line)
        if m:
            sources.append((m.group(1), _numbers(line)))
    added = 0
    out = []
    for sentence in re.split(r"(?<=[.!?])\s+", answer):
        nums = _significant(sentence)
        if nums and not re.search(r"\[\d{1,3}\]", sentence):
            n = next((n for n, have in sources if nums <= have), None)
            if n:
                body = sentence.rstrip()
                end = body[-1] if body and body[-1] in ".!?" else ""
                sentence = f"{body[: len(body) - len(end)]} [{n}]{end}"
                added += 1
        out.append(sentence)
    return " ".join(out), added


def get_llm(request: Request, settings: Settings) -> LocalLLM:
    factory = getattr(request.app.state, "llm_factory", None)
    return factory() if factory else LocalLLM(settings)


@router.post(
    "",
    response_model=ChatReply,
    responses={401: {"model": ErrorEnvelope}, 403: {"model": ErrorEnvelope}},
    summary="Ask about a company; answers cite SEC filings",
)
def chat(
    body: ChatRequest,
    request: Request,
    db: Session = Depends(db_session),
    settings: Settings = Depends(settings_dep),
    key=Depends(require_reader),
):
    who = getattr(key, "id", None) or (request.client.host if request.client else "unknown")
    decision = chat_limiter.check(f"chat:{who}", settings.chat_rate_limit_per_minute)
    if not decision.allowed:
        raise APIError(
            429,
            "rate_limited",
            f"At most {settings.chat_rate_limit_per_minute} chat questions per minute.",
            headers={"Retry-After": str(decision.retry_after_seconds)},
        )
    company = intel.resolve_company(db, body.message)
    if company is None and body.cik:
        try:
            cik = normalize_cik(body.cik)
        except ValueError as exc:
            raise APIError(422, "invalid_parameter", "cik must be numeric.") from exc
        company = db.scalar(select(Company).where(Company.cik == cik))

    if company is None:
        hits, _ = search_companies(db, body.message[:100], limit=5)
        return ChatReply(
            company=None,
            answer=None,
            brief=None,
            citations=[],
            checks={},
            model=None,
            suggestions=[_company_dict(h.company) for h in hits],
            notes=["Name a company (ticker, CIK or name) that this service has loaded."],
        )

    if getattr(request.state, "demo", False):
        from app.services.public import showcase_ciks

        allowed, _ = showcase_ciks(db, settings)
        if company.cik not in allowed:
            raise APIError(
                403, "demo_scope", "The demo key covers the public showcase companies only."
            )

    brief = intel.build_brief(db, company, as_of=body.as_of)
    brief_out = {
        "as_of": body.as_of.isoformat() if body.as_of else None,
        "metrics": brief.metrics,
        "filings": brief.filings,
        "leadership_filings": brief.leadership_filings,
        "coverage": brief.coverage,
    }
    notes = [DISCLAIMER]
    cov = brief.coverage
    if cov["stale"] and cov["last_filed"]:
        notes.append(
            f"The latest {company.legal_name} filing loaded here was filed {cov['last_filed']}; "
            "newer filings are not included."
        )
    if intel.is_leadership_question(body.message):
        answer = intel.leadership_answer(brief)
        return ChatReply(
            company=_company_dict(company),
            answer=answer,
            brief=brief_out,
            citations=brief.citations,
            checks=check_answer(answer, brief.context(), len(brief.citations)),
            model=None,
            answered_by="data",
            notes=notes,
        )
    answer, model, checks = None, None, {}
    try:
        reply = get_llm(request, settings).chat(
            [
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": f"CONTEXT:\n{brief.context()}\n\nQUESTION: {body.message}",
                },
            ]
        )
        answer, auto_cited = add_missing_citations(reply.text, brief.context_lines)
        model = reply.model
        checks = check_answer(answer, brief.context(), len(brief.citations))
        checks["auto_cited"] = auto_cited
        if not checks["grounded"]:
            notes.append(
                "Parts of the answer could not be matched to the cited data; they are listed "
                "under checks. Prefer the figures in the brief."
            )
    except LLMUnavailable as exc:
        notes.append(f"{exc} Showing the data brief only.")
    return ChatReply(
        company=_company_dict(company),
        answer=answer,
        brief=brief_out,
        citations=brief.citations,
        checks=checks,
        model=model,
        answered_by="model" if answer else None,
        notes=notes,
    )
