"""SEC comment letters (D-13, docs/contracts/comment-letters.md).

The SEC's letters to a company are UPLOAD filings (PDF, generated by the SEC with plain text
streams), the company's responses CORRESP filings (HTML or text). Each is read once through the
SEC client for its file number, subject, topics and whether the staff "completed its review".
Topics come from the reviewed keyword list below, never a model. Letters are grouped into one
review by file number; a gap of more than 180 days starts a new thread. The text is stored for
tagging only; responses never return it beyond short quoted snippets with the Archives link.
"""

from __future__ import annotations

import html as html_lib
import json
import re
import zlib
from datetime import date
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models import CommentLetter, Filing

FORMS = ("UPLOAD", "CORRESP")
READER = "letters-1"
SINCE = date(2019, 1, 1)
THREAD_GAP_DAYS = 180
TEXT_CHARS = 60_000
TOPICS = {  # key: (label, reviewed keyword pattern)
    "revenue_recognition": ("Revenue recognition", r"revenue recognition|asc 606|topic 606|"
                            r"performance obligations?|principal versus agent|gross versus net"),
    "non_gaap": ("Non-GAAP measures", r"non-gaap|regulation g\b|item 10\(e\)|adjusted ebitda|"
                 r"adjusted (?:net income|earnings|operating income)"),
    "segments": ("Segment reporting", r"reportable segments?|operating segments?|asc 280|"
                 r"chief operating decision maker|\bcodm\b"),
    "impairment": ("Impairment", r"impairment|goodwill"),
    "mdna": ("MD&A", r"management.s discussion and analysis|\bmd&a\b|known trends?|"
             r"liquidity and capital resources|critical accounting estimates?"),
    "income_taxes": ("Income taxes", r"income tax|valuation allowance|effective tax rate|asc 740"),
    "disclosure_controls": ("Disclosure controls", r"disclosure controls and procedures|"
                            r"internal control over financial reporting|material weakness"),
    "governance": ("Board and governance", r"leadership structure|item 407|lead director|"
                   r"board.s role in (?:the )?risk oversight|risk oversight"),
    "leases": ("Leases", r"asc 842|topic 842|lease liabilit|right-of-use"),
    "climate": ("Climate disclosure", r"climate|greenhouse gas|\bghg\b"),
    "cybersecurity": ("Cybersecurity", r"cybersecurity|item 1c\b|item 106"),
    "crypto": ("Crypto assets", r"crypto|digital assets?|bitcoin"),
    "going_concern": ("Going concern", r"going concern"),
    "related_parties": ("Related parties", r"related part(?:y|ies)"),
    # C-13b (2026-11-24): Item 402 disclosure, from a reviewed keyword list
    "executive_compensation": ("Executive compensation", r"item 402\b|402\(v\)|"
                               r"compensation discussion and analysis|\bcd&a\b|"
                               r"pay[- ]versus[- ]performance|summary compensation table|"
                               r"compensation actually paid|executive compensation"),
}  # fmt: skip
_TOPIC_RX = {k: re.compile(p, re.I) for k, (_, p) in TOPICS.items()}
TOPIC_LABELS = {k: v[0] for k, v in TOPICS.items()} | {"other": "Other"}
_FILE_NO = re.compile(r"File\s+Nos?\.?:?\s*((?:0\d{2}|333|811|814|024|000)-\d{4,6})", re.I)
_RE = re.compile(r"\bRe:\s*(.{10,300}?)(?:\s+File\s+No|\s+Dear\b|\s+Ladies\b|$)", re.I | re.S)
_CLOSES = re.compile(r"(?:completed|concluded) (?:its|our) review", re.I)
_NO_REVIEW = re.compile(r"have not reviewed and will not review", re.I)
_ACCEL = re.compile(r"request(?:s|ed)? (?:that )?(?:the )?(?:acceleration|effective(?:ness)?)|"
                    r"accelerat\w* (?:of )?the effective (?:date|time)|Rule 461", re.I)  # fmt: skip
# the SEC's closing boilerplate repeats words that are not the letter's subject
_BOILER = re.compile(r"We remind you that.*?(?:staff\.|$)|Please contact .*$", re.I | re.S)


_TEXT_OPS = re.compile(rb"\((.*?)(?<!\\)\)\s*Tj|\[(.*?)\]\s*TJ|(T\*|Td|TD|ET)", re.S)


def pdf_text(data: bytes) -> str:
    """Text of an SEC-generated PDF: its deflated content streams' text operators. Scanned or
    font-encoded PDFs give little or nothing, and are marked not readable."""
    out: list[bytes] = []
    for raw in re.findall(rb"stream\r?\n(.*?)\r?\nendstream", data, re.S):
        try:
            content = zlib.decompress(raw)
        except zlib.error:
            continue
        for m in _TEXT_OPS.finditer(content):
            if m.group(1) is not None:
                out.append(m.group(1))
            elif m.group(2) is not None:
                out.append(b"".join(re.findall(rb"\((.*?)(?<!\\)\)", m.group(2))))
            else:
                out.append(b" ")
    text = b"".join(out).decode("latin-1")
    text = re.sub(r"\\([()\\])", r"\1", text)
    return " ".join(text.split())


def html_text(doc: str) -> str:
    doc = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", doc)
    return " ".join(html_lib.unescape(re.sub(r"<[^>]+>", " ", doc)).split())


def topics(text: str) -> list[str]:
    body = _BOILER.sub(" ", text or "")
    found = [k for k, rx in _TOPIC_RX.items() if rx.search(body)]
    return found


def parse(text: str, form: str) -> dict:
    head = text[:3000]
    fno = _FILE_NO.search(text)
    subj = _RE.search(head)
    kind = "letter"
    if form == "CORRESP" and _ACCEL.search(head) and len(text) < 6000:
        kind = "acceleration_request"
    no_review = form == "UPLOAD" and bool(_NO_REVIEW.search(text))
    if no_review:
        kind = "no_review"  # "we have not reviewed and will not review your registration"
    closes = form == "UPLOAD" and (no_review or bool(_CLOSES.search(text)))
    tags = [] if kind != "letter" or closes else topics(text)
    return {
        "file_number": fno.group(1) if fno else None,
        "subject": " ".join(subj.group(1).split())[:300] if subj else None,
        "kind": kind, "closes_review": closes,
        "topics": tags or ([] if (kind != "letter" or closes or not text) else ["other"]),
    }  # fmt: skip


def _doc_url(f: Filing) -> str:
    return (f"https://www.sec.gov/Archives/edgar/data/{int(f.cik)}/"
            f"{f.accession_number.replace('-', '')}/{f.primary_document}")  # fmt: skip


def read(db: Session, sec, f: Filing, tmp: Path) -> dict:
    """Fetch and parse one letter (not stored here)."""
    url = _doc_url(f)
    if (f.primary_document or "").lower().endswith(".pdf"):
        dest = tmp / f"{f.accession_number}.pdf"
        sec.download_file(url, dest, max_bytes=20_000_000)
        text = pdf_text(dest.read_bytes())
        dest.unlink(missing_ok=True)
        dest.with_suffix(".pdf.meta.json").unlink(missing_ok=True)
    else:
        text = html_text(sec.get_text(url).data)
    readable = len(text) >= 200
    p = parse(text if readable else "", f.form_type)
    return {
        "accession_number": f.accession_number, "cik": f.cik, "form_type": f.form_type,
        "filing_date": f.filing_date, **p, "topics": json.dumps(p["topics"]),
        "readable": readable, "text": text[:TEXT_CHARS] if readable else None,
        "source_url": f.source_url, "reader_version": READER,
    }  # fmt: skip


def letters_to_read(db: Session, ciks: list[str], since: date = SINCE) -> list[Filing]:
    have = set(db.scalars(select(CommentLetter.accession_number)))
    out, seen = [], set(have)
    for f in db.scalars(select(Filing).where(
            Filing.cik.in_(ciks), Filing.form_type.in_(FORMS), Filing.filing_date >= since,
            Filing.primary_document.is_not(None)).order_by(Filing.filing_date)):  # fmt: skip
        if f.accession_number not in seen:
            seen.add(f.accession_number)
            out.append(f)
    return out


# -- read side ------------------------------------------------------------------------------


def _threads(rows: list[CommentLetter]) -> list[list[CommentLetter]]:
    rows = sorted(rows, key=lambda r: (r.filing_date, r.accession_number))
    by_file: dict[str, list[list[CommentLetter]]] = {}
    loose: list[CommentLetter] = []
    for r in rows:
        if r.kind == "acceleration_request":
            continue
        if not r.file_number:
            loose.append(r)
            continue
        threads = by_file.setdefault(r.file_number, [])
        if threads and (r.filing_date - threads[-1][-1].filing_date).days <= THREAD_GAP_DAYS \
                and not threads[-1][-1].closes_review:  # fmt: skip
            threads[-1].append(r)
        else:
            threads.append([r])
    out = [t for ts in by_file.values() for t in ts]
    for r in loose:  # a letter without a file number joins the open thread nearest in time
        near = [t for t in out if 0 <= (r.filing_date - t[-1].filing_date).days <= THREAD_GAP_DAYS
                and not t[-1].closes_review]  # fmt: skip
        if near:
            min(near, key=lambda t: (r.filing_date - t[-1].filing_date).days).append(r)
        else:
            out.append([r])
    return out


def for_company(db: Session, cik: str, since: date | None = None, topic: str | None = None,
                limit: int = 20, read_set: bool = True,
                as_of: date | None = None) -> dict:  # fmt: skip
    """as_of (chat): only letters filed by then, so a review closed later shows as open."""
    since = since or (as_of or date.today()).replace(year=(as_of or date.today()).year - 5)
    q = select(CommentLetter).where(CommentLetter.cik == cik)
    if as_of:
        q = q.where(CommentLetter.filing_date <= as_of)
    rows = list(db.scalars(q))
    out_threads = []
    for t in _threads(rows):
        if t[-1].filing_date < since:
            continue
        # the staff's letters say what was questioned; a response's own wording adds noise
        sec = [r for r in t if r.form_type == "UPLOAD" and r.readable and not r.closes_review]
        basis = sec or [r for r in t if r.form_type == "CORRESP"]
        if any(r.kind == "no_review" for r in t):
            basis = []  # the staff did not review: a response's wording is not a topic
        tags = sorted({x for r in basis for x in json.loads(r.topics)} - {"other"}) or (
            ["other"] if any(json.loads(r.topics) for r in basis) else []
        )
        if topic and topic not in tags:
            continue
        first_sec = next((r for r in t if r.form_type == "UPLOAD"), t[0])
        closed = next((r for r in t if r.closes_review), None)
        out_threads.append({
            "id": t[0].accession_number, "file_number": t[0].file_number or next(
                (r.file_number for r in t if r.file_number), None),
            "subject": first_sec.subject or next((r.subject for r in t if r.subject), None),
            "opened": t[0].filing_date.isoformat(),
            "closed": closed.filing_date.isoformat() if closed else None,
            "status": "closed" if closed else "open_or_unknown", "topics": tags,
            "letters": [{
                "date": r.filing_date.isoformat(), "from": "sec" if r.form_type == "UPLOAD"
                else "company", "form": r.form_type, "accession_number": r.accession_number,
                "topics": [x for x in json.loads(r.topics) if x != "other"],
                "readable": r.readable, "source_url": r.source_url,
            } for r in t],
        })  # fmt: skip
    out_threads.sort(key=lambda x: x["opened"], reverse=True)
    body = {"cik": cik, "threads": out_threads[:limit], "topic_keys": TOPIC_LABELS,
            "notes": ["Topics are tagged from a reviewed keyword list; a letter can have several. "
                      "The SEC releases its review correspondence at least 20 business days "
                      "after a review closes."]}  # fmt: skip
    any_read = select(CommentLetter.accession_number).where(CommentLetter.cik == cik).limit(1)
    read = bool(rows) or (as_of is not None and db.scalar(any_read) is not None)
    if not read:
        lq = select(Filing).where(Filing.cik == cik, Filing.form_type.in_(FORMS),
                                  Filing.filing_date >= since)  # fmt: skip
        if as_of:
            lq = lq.where(Filing.filing_date <= as_of)
        listed = list(db.scalars(lq.order_by(Filing.filing_date.desc()).limit(limit * 3)))
        body["coverage"] = "not_read"
        body["letters"] = [{"date": f.filing_date.isoformat(),
                            "from": "sec" if f.form_type == "UPLOAD" else "company",
                            "form": f.form_type, "accession_number": f.accession_number,
                            "source_url": f.source_url} for f in listed]  # fmt: skip
    else:
        body["coverage"] = "read"
    return body
